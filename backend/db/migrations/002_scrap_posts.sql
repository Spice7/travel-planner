-- 스크랩 2단계: 붙여 넣은 글 스크랩과 사용자가 확인하는 라벨.
-- 적용: psql -h localhost -U <user> -d postDB -v ON_ERROR_STOP=1 -f backend/db/migrations/002_scrap_posts.sql
-- 다시 실행해도 안전하다.

BEGIN;

-- 글 스크랩의 중복 판단용: 공백을 정리한 본문의 sha256. 같은 글을 같은 장소로 두 번 저장하지 못한다.
ALTER TABLE public.scraps ADD COLUMN IF NOT EXISTS content_hash VARCHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS ux_scraps_user_place_content
    ON public.scraps (user_id, place_id, content_hash)
    WHERE content_hash IS NOT NULL;

-- 주소 없이 붙여 넣은 글도 review_id·source_url이 비어 있어, 장소 찜을 source_type으로 구분한다.
DROP INDEX IF EXISTS public.ux_scraps_user_place;
CREATE UNIQUE INDEX ux_scraps_user_place
    ON public.scraps (user_id, place_id)
    WHERE source_type = 'internal' AND review_id IS NULL;

-- 본문에서 찾은 홍보 문구와 모델이 뽑은 동행 유형
ALTER TABLE public.scrap_contents ADD COLUMN IF NOT EXISTS promo_signals JSONB NOT NULL DEFAULT '[]';
ALTER TABLE public.scrap_contents ADD COLUMN IF NOT EXISTS traveler_context JSONB NOT NULL DEFAULT '[]';

-- 글 스크랩에서 모델이 뽑은 라벨. 사용자가 확정(confirmed)한 것만 그 사용자의 비교 추천에 쓴다.
-- 제외(rejected)한 라벨도 남겨 aspect별 제외율을 볼 수 있게 한다.
CREATE TABLE IF NOT EXISTS public.scrap_annotations (
    annotation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrap_id BIGINT NOT NULL REFERENCES public.scraps(scrap_id) ON DELETE CASCADE,
    aspect_id BIGINT NOT NULL REFERENCES public.aspects(aspect_id) ON DELETE RESTRICT,
    attribute_value VARCHAR(100) NOT NULL,
    sentiment VARCHAR(10) NOT NULL CHECK (sentiment IN ('positive', 'negative', 'neutral')),
    evidence_text TEXT NOT NULL,
    evidence_start INTEGER NOT NULL,
    evidence_end INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'suggested' CHECK (status IN ('suggested', 'confirmed', 'rejected')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (evidence_start >= 0 AND evidence_end > evidence_start)
);
CREATE INDEX IF NOT EXISTS idx_scrap_annotations_scrap ON public.scrap_annotations (scrap_id);

COMMIT;
